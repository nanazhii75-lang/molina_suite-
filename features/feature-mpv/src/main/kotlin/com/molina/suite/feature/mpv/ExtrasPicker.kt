package com.molina.suite.feature.mpv

/** Satu trek subtitle mentah dari Extractor, sebelum disaring [ExtrasPicker]. */
internal data class RawSubtitle(
    val lang: String,
    val label: String,
    val ext: String,
    val url: String,
    val autoGenerated: Boolean
)

/**
 * Menyaring bab dan subtitle dari Extractor menjadi bentuk yang aman dibaca ytdl_hook mpv.
 * Murni (tanpa kelas NewPipe) agar bisa diuji di JVM.
 */
internal object ExtrasPicker {

    private const val MAX_CHAPTERS = 200
    private const val MIN_CHAPTERS = 2
    private const val MAX_SUBTITLES = 12
    private const val MAX_TEXT_CHARS = 200
    private const val AUTO_SUFFIX = "-auto"
    private const val AUTO_LABEL = " (otomatis)"

    private val LANG = Regex("[A-Za-z0-9_-]{1,35}")
    private val TTML_FORMAT = Regex("([?&])fmt=ttml(?=&|$)")
    private val EXT_ORDER = listOf("vtt", "srt")

    /**
     * Bab terurut menurut waktu mulai, tanpa duplikat, dan di dalam durasi video. Kurang dari
     * dua bab dianggap tidak ada bab (satu bab tidak berguna di seekbar).
     */
    fun chapters(raw: List<Pair<Int, String>>, durationSec: Long): List<ChapterItem> {
        val cleaned = raw.asSequence()
            .filter { (start, _) -> start >= 0 && (durationSec <= 0 || start < durationSec) }
            .map { (start, title) -> ChapterItem(start, cleanText(title)) }
            .sortedBy { it.startSec }
            .distinctBy { it.startSec }
            .take(MAX_CHAPTERS)
            .toList()
        return if (cleaned.size >= MIN_CHAPTERS) cleaned else emptyList()
    }

    /**
     * Subtitle manual lebih dulu, lalu otomatis; paling banyak [MAX_SUBTITLES]. Hanya HTTPS dan
     * format VTT/SRT. TTML dari timedtext YouTube diminta ulang sebagai VTT. Subtitle otomatis
     * memakai kunci "<bahasa>-auto" agar tidak dipilih otomatis oleh pengaturan bahasa mpv.
     */
    fun subtitles(raw: List<RawSubtitle>): List<SubtitleItem> {
        val best = LinkedHashMap<String, RawSubtitle>()
        for (item in raw) {
            val normalized = normalize(item) ?: continue
            val key = keyOf(normalized)
            val current = best[key]
            if (current == null || rank(normalized.ext) < rank(current.ext)) best[key] = normalized
        }
        return best.values
            .sortedBy { it.autoGenerated }
            .take(MAX_SUBTITLES)
            .map { SubtitleItem(keyOf(it), it.ext, it.url, nameOf(it)) }
    }

    private fun normalize(item: RawSubtitle): RawSubtitle? {
        val lang = item.lang.trim()
        if (!LANG.matches(lang)) return null
        var url = item.url.trim()
        if (!url.startsWith("https://")) return null
        var ext = item.ext.trim().lowercase()
        if (ext == "ttml" && TTML_FORMAT.containsMatchIn(url)) {
            url = TTML_FORMAT.replace(url, "\$1fmt=vtt")
            ext = "vtt"
        }
        if (ext !in EXT_ORDER) return null
        return item.copy(lang = lang, url = url, ext = ext)
    }

    private fun rank(ext: String): Int = EXT_ORDER.indexOf(ext)

    private fun keyOf(item: RawSubtitle): String =
        if (item.autoGenerated) item.lang + AUTO_SUFFIX else item.lang

    private fun nameOf(item: RawSubtitle): String {
        val label = cleanText(item.label).ifEmpty { item.lang }
        return if (item.autoGenerated) label + AUTO_LABEL else label
    }

    private fun cleanText(text: String): String =
        text.filter { !it.isISOControl() }.trim().take(MAX_TEXT_CHARS)
}
